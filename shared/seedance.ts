/** 确定性拼装：把字段拼成一条 Seedance 图生视频提示词（无 LLM 回退 / 预览用） */
export function assembleSeedancePrompt(f: SeedanceFields, hasHuman = true): string {
  const parts: string[] = []
  if (f.shot) parts.push(f.shot)
  if (f.subject) parts.push(f.subject)
  if (f.action) parts.push(f.action)
  if (f.environment) parts.push(f.environment)
  if (f.camera) parts.push(f.camera)
  if (f.lighting) parts.push(f.lighting)
  if (f.style) parts.push(f.style)
  parts.push(Object.values(SEEDANCE_ANCHORS).join('，'))
  if (hasHuman) parts.push(SEEDANCE_NEGATIVE_HUMAN)
  let prompt = parts.filter(Boolean).join('，') + '。'
  prompt = '@图片1作为首帧。' + prompt
  const tail: string[] = []
  if (f.durationSec) tail.push(`${f.durationSec}秒`)
  if (f.aspectRatio) tail.push(f.aspectRatio)
  if (tail.length) prompt += `（${tail.join('，')}）`
  return prompt
}

